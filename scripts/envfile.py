import os
from pathlib import Path


def load_env(path=None):
    """Load KEY=VALUE lines from the project's .env into os.environ.
    Variables that are already set are left alone, so a value set by hand still wins."""
    env_path = Path(path) if path else Path(__file__).resolve().parent.parent / ".env"
    if not env_path.exists():
        return
    for line in env_path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        if line.startswith("export "):
            line = line[len("export "):]
        key, value = line.split("=", 1)
        key, value = key.strip(), value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        else:
            value = value.split(" #", 1)[0].strip()   # inline comment, like docker compose does
        os.environ.setdefault(key, value)